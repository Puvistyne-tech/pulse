export type CampusId = string;
export type SessionId = string;
export type AccountId = string;
export type RoomId = string;
export type MessageId = string;
export type ClientNonce = string;
export type ProtocolVersion = number;
export type AuthToken = string;
export type AccountProfile = { account_id: AccountId, email: string, display_name: string, };
export type SignUpRequest = { email: string, display_name: string, password: string, };
export type SignInRequest = { email: string, password: string, };
export type AuthSession = { account: AccountProfile, token: AuthToken, };
export type Role = "owner" | "admin" | "member" | "guest";
export type Permission = "view_campus" | "view_rooms" | "create_room" | "manage_members" | "manage_campus" | "post_message";
export type Room = { room_id: RoomId, campus_id: CampusId, slug: string, };
export type CampusSummary = { campus_id: CampusId, slug: string, display_name: string, role: Role, };
export type CreateCampusRequest = { slug: string, display_name: string, };
export type CampusCreated = { campus: CampusSummary, rooms: Array<Room>, };
export type CampusList = { campuses: Array<CampusSummary>, };
export type RoomList = { campus_id: CampusId, rooms: Array<Room>, };
export type CreateRoomRequest = { slug: string, };
export type ApiErrorCode = "invalid_input" | "unauthenticated" | "forbidden" | "not_found" | "conflict" | "unavailable" | "internal";
export type InputField = "email" | "display_name" | "password" | "slug" | "message_body";
export type ApiError = { code: ApiErrorCode, field: InputField | null, };
export type HandshakeRejection = "unauthenticated" | "campus_unavailable";
export type HandshakeRejected = { reason: HandshakeRejection, };
export type Hello = { protocol_version: ProtocolVersion, campus_id: CampusId, auth_token: AuthToken, };
export type Welcome = { protocol_version: ProtocolVersion, campus_id: CampusId, session_id: SessionId, account_id: AccountId, role: Role, };
export type Ping = { nonce: number, };
export type Pong = { nonce: number, };
export type VersionMismatch = { supported: ProtocolVersion, received: ProtocolVersion, };
export type RoomMessage = { message_id: MessageId, previous_message_id: MessageId | null, campus_id: CampusId, room_id: RoomId, author_id: AccountId, author_display_name: string, client_nonce: ClientNonce, body: string, };
export type SendMessage = { room_id: RoomId, client_nonce: ClientNonce, body: string, };
export type RoomCursor = { room_id: RoomId, after: MessageId | null, };
export type SyncRooms = { cursors: Array<RoomCursor>, };
export type MessageAccepted = { message: RoomMessage, };
export type MessageCreated = { message: RoomMessage, };
export type MessageRejection = "forbidden" | "invalid_body" | "unknown_room";
export type MessageRejected = { client_nonce: ClientNonce, reason: MessageRejection, };
export type RoomSynced = { room_id: RoomId, messages: Array<RoomMessage>, has_more: boolean, };
export type RoomUnavailable = { room_id: RoomId, };
export type ClientFrame = { "type": "hello" } & Hello | { "type": "ping" } & Ping | { "type": "send_message" } & SendMessage | { "type": "sync_rooms" } & SyncRooms;
export type ServerFrame = { "type": "welcome" } & Welcome | { "type": "pong" } & Pong | { "type": "version_mismatch" } & VersionMismatch | { "type": "handshake_rejected" } & HandshakeRejected | { "type": "message_accepted" } & MessageAccepted | { "type": "message_created" } & MessageCreated | { "type": "message_rejected" } & MessageRejected | { "type": "room_synced" } & RoomSynced | { "type": "room_unavailable" } & RoomUnavailable;
export type ConnectionPhase = "disconnected" | "connecting" | "handshaking" | "connected" | "backoff";
export type AuthPhase = "signed_out" | "authenticating" | "signed_in";
export type ConnectionSnapshot = { protocol_version: ProtocolVersion, connection: ConnectionPhase, retry_in_ms: number | null, campus_id: CampusId | null, session_id: SessionId | null, attempt: number, rejection: VersionMismatch | null, handshake_rejection: HandshakeRejection | null, };
export type SessionSnapshot = { auth: AuthPhase, account: AccountProfile | null, campuses: Array<CampusSummary>, active_campus_id: CampusId | null, rooms: Array<Room>, active_room_id: RoomId | null, busy: boolean, error: ApiError | null, };
export type DeliveryState = "pending" | "confirmed" | "failed";
export type TimelineEntry = { client_nonce: ClientNonce, message_id: MessageId | null, author_id: AccountId, author_display_name: string, from_self: boolean, body: string, delivery: DeliveryState, rejection: MessageRejection | null, };
export type TimelineSnapshot = { room_id: RoomId | null, entries: Array<TimelineEntry>, syncing: boolean, error: ApiError | null, };
export type ClientSnapshot = { sequence: number, network: ConnectionSnapshot, session: SessionSnapshot, timeline: TimelineSnapshot, };
