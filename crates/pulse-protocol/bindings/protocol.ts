export type CampusId = string;
export type SessionId = string;
export type AccountId = string;
export type RoomId = string;
export type ProtocolVersion = number;
export type AuthToken = string;
export type AccountProfile = { account_id: AccountId, email: string, display_name: string, };
export type SignUpRequest = { email: string, display_name: string, password: string, };
export type SignInRequest = { email: string, password: string, };
export type AuthSession = { account: AccountProfile, token: AuthToken, };
export type Role = "owner" | "admin" | "member" | "guest";
export type Permission = "view_campus" | "view_rooms" | "create_room" | "manage_members" | "manage_campus";
export type Room = { room_id: RoomId, campus_id: CampusId, slug: string, };
export type CampusSummary = { campus_id: CampusId, slug: string, display_name: string, role: Role, };
export type CreateCampusRequest = { slug: string, display_name: string, };
export type CampusCreated = { campus: CampusSummary, rooms: Array<Room>, };
export type CampusList = { campuses: Array<CampusSummary>, };
export type RoomList = { campus_id: CampusId, rooms: Array<Room>, };
export type CreateRoomRequest = { slug: string, };
export type ApiErrorCode = "invalid_input" | "unauthenticated" | "forbidden" | "not_found" | "conflict" | "unavailable" | "internal";
export type InputField = "email" | "display_name" | "password" | "slug";
export type ApiError = { code: ApiErrorCode, field: InputField | null, };
export type HandshakeRejection = "unauthenticated" | "campus_unavailable";
export type HandshakeRejected = { reason: HandshakeRejection, };
export type Hello = { protocol_version: ProtocolVersion, campus_id: CampusId, auth_token: AuthToken, };
export type Welcome = { protocol_version: ProtocolVersion, campus_id: CampusId, session_id: SessionId, account_id: AccountId, role: Role, };
export type Ping = { nonce: number, };
export type Pong = { nonce: number, };
export type VersionMismatch = { supported: ProtocolVersion, received: ProtocolVersion, };
export type ClientFrame = { "type": "hello" } & Hello | { "type": "ping" } & Ping;
export type ServerFrame = { "type": "welcome" } & Welcome | { "type": "pong" } & Pong | { "type": "version_mismatch" } & VersionMismatch | { "type": "handshake_rejected" } & HandshakeRejected;
export type ConnectionPhase = "disconnected" | "connecting" | "handshaking" | "connected" | "backoff";
export type AuthPhase = "signed_out" | "authenticating" | "signed_in";
export type ConnectionSnapshot = { protocol_version: ProtocolVersion, connection: ConnectionPhase, retry_in_ms: number | null, campus_id: CampusId | null, session_id: SessionId | null, attempt: number, rejection: VersionMismatch | null, handshake_rejection: HandshakeRejection | null, };
export type SessionSnapshot = { auth: AuthPhase, account: AccountProfile | null, campuses: Array<CampusSummary>, active_campus_id: CampusId | null, rooms: Array<Room>, busy: boolean, error: ApiError | null, };
export type ClientSnapshot = { network: ConnectionSnapshot, session: SessionSnapshot, };
